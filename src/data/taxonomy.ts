/**
 * Given any path (DE or EN), finds the matching TaxonomyRoute or product match
 */
export function findRouteByPath(rawPath: string): {
  route?: TaxonomyRoute;
  isProduct?: boolean;
  productSlug?: string;
  isBrandDetail?: boolean;
  brandSlug?: string;
} {
  const norm = normalizePath(rawPath);

  // Check product match: /e-bike/<slug>/ or /en/e-bike/<slug>/
  const productDeMatch = norm.match(/^\/e-bike\/([^/]+)\/$/);
  const productEnMatch = norm.match(/^\/en\/e-bike\/([^/]+)\/$/);
  if (productDeMatch) {
    return { isProduct: true, productSlug: productDeMatch[1] };
  }
  if (productEnMatch) {
    return { isProduct: true, productSlug: productEnMatch[1] };
  }

  // Check brand detail: /marken/<brand>/ or /en/brands/<brand>/
  const brandDeMatch = norm.match(/^\/marken\/([^/]+)\/$/);
  const brandEnMatch = norm.match(/^\/en\/brands\/([^/]+)\/$/);
  if (brandDeMatch && brandDeMatch[1] !== '') {
    return { isBrandDetail: true, brandSlug: brandDeMatch[1] };
  }
  if (brandEnMatch && brandEnMatch[1] !== '') {
    return { isBrandDetail: true, brandSlug: brandEnMatch[1] };
  }

  // Exact match from taxonomy
  const found = TAXONOMY_ROUTES.find(
    (r) => r.pathDe === norm || r.pathEn === norm
  );
  if (found) return { route: found };

  // Fallback match without trailing slash check
  const altFound = TAXONOMY_ROUTES.find(
    (r) =>
      r.pathDe.replace(/\/$/, '') === norm.replace(/\/$/, '') ||
      r.pathEn.replace(/\/$/, '') === norm.replace(/\/$/, '')
  );
  if (altFound) return { route: altFound };

  return {};
}

/**
 * Switches the current path to the target language equivalent
 */
export function translatePath(currentPath: string, targetLang: 'de' | 'en'): string {
  const norm = normalizePath(currentPath);

  // Check product detail
  const prodMatch = findRouteByPath(norm);
  if (prodMatch.isProduct && prodMatch.productSlug) {
    return targetLang === 'en'
      ? `/en/e-bike/${prodMatch.productSlug}/`
      : `/e-bike/${prodMatch.productSlug}/`;
  }

  // Check brand detail
  if (prodMatch.isBrandDetail && prodMatch.brandSlug) {
    return targetLang === 'en'
      ? `/en/brands/${prodMatch.brandSlug}/`
      : `/marken/${prodMatch.brandSlug}/`;
  }

  // Taxonomy route match
  const match = TAXONOMY_ROUTES.find(
    (r) => r.pathDe === norm || r.pathEn === norm
  );
  if (match) {
    return targetLang === 'en' ? match.pathEn : match.pathDe;
  }

  // Fallback: if already starts with /en/
  if (targetLang === 'de') {
    if (norm === '/en/') return '/';
    return norm.replace(/^\/en/, '') || '/';
  } else {
    if (norm === '/') return '/en/';
    return `/en${norm}`;
  }
}

